"""Compile the REAL overlay speed page and drive its buttons.

The SetSpeed / RestoreSpeed / RenderSpeed method bodies are extracted verbatim from the
production mods/CesiumOverlayMod/OverlayWindow.cs at run time; the harness stubs only the
Unity / FairyGUI / Android surface and the LocalSpeed backend. If a method disappears or is
renamed the extraction fails loudly instead of silently testing a stale copy.
"""
import argparse
from pathlib import Path
import subprocess
import sys

METHODS = [
    ('private void SetSpeed(double target)', 'SetSpeed'),
    ('private void RestoreSpeed()', 'RestoreSpeed'),
    ('private void RenderSpeed()', 'RenderSpeed'),
]


def extract_method(text, signature):
    start = text.find(signature)
    if start < 0:
        raise SystemExit('production source no longer contains: ' + signature)
    if text.find(signature, start + 1) >= 0:
        raise SystemExit('ambiguous signature, appears more than once: ' + signature)
    brace = text.index('{', start + len(signature))
    depth = 0
    i = brace
    while i < len(text):
        ch = text[i]
        if ch == '"':
            i += 1
            while i < len(text) and text[i] != '"':
                i += 2 if text[i] == '\\' else 1
        elif ch == "'":
            i += 1
            while i < len(text) and text[i] != "'":
                i += 2 if text[i] == '\\' else 1
        elif ch == '/' and i + 1 < len(text) and text[i + 1] == '/':
            while i < len(text) and text[i] != '\n':
                i += 1
            continue
        elif ch == '/' and i + 1 < len(text) and text[i + 1] == '*':
            end = text.find('*/', i + 2)
            i = len(text) if end < 0 else end + 2
            continue
        elif ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    raise SystemExit('unbalanced braces after: ' + signature)


parser = argparse.ArgumentParser()
parser.add_argument('--compiler', type=Path, required=True, help='Roslyn csc.dll')
parser.add_argument('--refs', type=Path, required=True, help='.NET 8 reference assembly directory')
args = parser.parse_args()
here = Path(__file__).resolve().parent
repo = here.parents[2]
production = repo / 'mods/CesiumOverlayMod'
window_source = (production / 'OverlayWindow.cs').read_text(encoding='utf-8')

extracted = [extract_method(window_source, signature) for signature, _ in METHODS]
output = repo / 'build/speedpanel-tests'
output.mkdir(parents=True, exist_ok=True)
generated = output / 'generated/SpeedPageExtract.cs'
generated.parent.mkdir(parents=True, exist_ok=True)
header = [
    '// GENERATED by mods/tests/speedpanel/run.py -- verbatim method bodies copied from',
    '// mods/CesiumOverlayMod/OverlayWindow.cs. Do not edit; re-run the runner instead.',
    'using System;',
    'using System.Collections.Generic;',
    'using System.Globalization;',
    'using CesiumAndroid;',
    'using FairyGUI;',
    'using UnityEngine;',
    '',
    'namespace CesiumOverlayMod',
    '{',
    '    public sealed partial class OverlayController',
    '    {',
]
body = []
for method in extracted:
    body.extend('        ' + line if line.strip() else line for line in method.splitlines())
generated.write_text('\n'.join(header + body + ['    }', '}', '']), encoding='utf-8')
print('extracted methods:' + ''.join('\n  ' + name + ' (' + str(len(text)) + ' chars)'
                                     for text, (_, name) in zip(extracted, METHODS)))

references = sorted(args.refs.glob('*.dll'))
if not args.compiler.is_file() or not references:
    raise SystemExit('Provide an existing compiler and .NET 8 reference assemblies.')
assembly = output / 'SpeedPanelTests.dll'
sources = [
    generated,
    production / 'SpeedPanel.cs',
    production / 'DockState.cs',
    production / 'OverlayOptions.cs',
    here / 'Stubs.cs',
    here / 'RenderStub.cs',
    here / 'Program.cs',
]
options = ['-nologo', '-nostdlib+', '-langversion:latest', '-target:exe', '-out:' + str(assembly)]
options += ['-r:' + str(path.resolve()) for path in references]
options += [str(path) for path in sources]
response = output / 'compile.rsp'
response.write_text('\n'.join('"' + option + '"' for option in options), encoding='utf-8')
compile_result = subprocess.run(['dotnet', str(args.compiler.resolve()), '@' + str(response)])
if compile_result.returncode != 0:
    raise SystemExit(compile_result.returncode)
assembly.with_suffix('.runtimeconfig.json').write_text(
    '{"runtimeOptions":{"tfm":"net8.0","framework":{"name":"Microsoft.NETCore.App","version":"8.0.0"}}}',
    encoding='utf-8')
raise SystemExit(subprocess.run(['dotnet', str(assembly)]).returncode)
